/**
 * Report branding on the screen side: what a PDF and a shared report say about who prepared them. The server decides what a
 * name may be (api-server lib/branding.ts) and sends it with the report; this only words it, and checks the shape of what
 * arrived before using it. A name is only ever rendered as text.
 */

export interface Brand { name: string; poweredBy: boolean }

export const BRAND_MAX = 60;

/** The brand in a report response (`brand` beside the report), or null when there is none or it is not the expected shape. */
export function brandOf(response: unknown): Brand | null {
  const b = (response as { brand?: unknown } | null | undefined)?.brand as { name?: unknown; poweredBy?: unknown } | null | undefined;
  if (!b || typeof b.name !== "string" || b.name.trim() === "" || b.name.length > BRAND_MAX) return null;
  return { name: b.name, poweredBy: b.poweredBy !== false };
}

/** The line at the foot of every PDF page. */
export function pdfFooter(brand: Brand | null, origin: string, scanned: string): string {
  if (!brand) return `Generated by SecScan · ${origin} · scanned ${scanned}`;
  return brand.poweredBy
    ? `Prepared by ${brand.name} · scanned ${scanned} · generated by SecScan`
    : `Prepared by ${brand.name} · scanned ${scanned}`;
}

/** The file name: the brand's own words for a branded report, so the file does not advertise another name. */
export function pdfFilename(brand: Brand | null, host: string | null): string {
  const slug = brand ? brand.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 30) : "secscan";
  const stem = slug || "security";
  return host ? `${stem}-${host}.pdf` : `${stem}-report.pdf`;
}

/** What the shared report page says at its foot. */
export function sharedFooter(brand: Brand | null): { prepared: string | null; showSecScanCredit: boolean; showScanCta: boolean } {
  if (!brand) return { prepared: null, showSecScanCredit: true, showScanCta: true };
  return { prepared: `Prepared by ${brand.name}`, showSecScanCredit: brand.poweredBy, showScanCta: brand.poweredBy };
}
