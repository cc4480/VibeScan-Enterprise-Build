/**
 * Turns an on-screen element into a multi-page A4 PDF without cutting through anything.
 *
 * The old export drew the whole report as one tall image and sliced it every 297 mm, so a page
 * boundary landed wherever it landed: through a heading ("AI Analysis" torn across two pages),
 * through a finding, through a line of text. Here the element marks its sections with
 * `data-pdf-block`, and a page only ever ends between two blocks. A block taller than a page
 * cannot be kept whole and is sliced, which is the only time text is cut.
 */

export interface Block {
  /** Top and bottom in canvas pixels, measured from the top of the captured element. */
  top: number;
  bottom: number;
}

export interface PagePlan {
  /** The slice of the captured image this page shows, in canvas pixels. */
  start: number;
  end: number;
}

/**
 * Decide which slice of the tall image goes on each page.
 *
 * Greedy: fill the page with as many whole blocks as fit, end it at the bottom of the last one,
 * and start the next page at the top of the next block (dropping the gap between them, which is
 * just whitespace). If not even one block fits, slice at the page height.
 */
export function planPages(blocks: Block[], totalHeight: number, pageHeight: number): PagePlan[] {
  if (pageHeight <= 0 || totalHeight <= 0) return [];
  const ordered = [...blocks].filter((b) => b.bottom > b.top).sort((a, b) => a.top - b.top);
  const pages: PagePlan[] = [];
  let start = 0;
  // A generous ceiling: a report cannot need more pages than this, so a bug cannot loop forever.
  for (let guard = 0; guard < 500 && start < totalHeight - 1; guard++) {
    const limit = start + pageHeight;
    if (limit >= totalHeight) {
      pages.push({ start, end: totalHeight });
      break;
    }
    let cut = -1;
    for (const b of ordered) {
      if (b.bottom <= limit && b.bottom > start + 1) cut = b.bottom;
    }
    // Nothing whole fits from here (one block taller than a page): slice at the limit.
    const sliced = cut < 0;
    if (sliced) cut = limit;
    pages.push({ start, end: cut });
    if (sliced) {
      start = cut;
    } else {
      const next = ordered.find((b) => b.top >= cut - 0.5);
      start = next ? Math.max(cut, next.top) : cut;
    }
  }
  return pages;
}

export interface ExportOptions {
  filename: string;
  /** Left side of the footer on every page, e.g. "Generated by SecScan · secscan.us · 24 Sep 2026". */
  footer: string;
  /** The app's page background, painted behind every page. */
  background?: string;
  /** Text colour for the footer. */
  footerColor?: string;
}

const A4_RATIO = 297 / 210;

export async function exportElementToPdf(container: HTMLElement, opts: ExportOptions): Promise<void> {
  // html2canvas-pro, not html2canvas: this app's Tailwind colours are oklch(), which html2canvas 1.4.1
  // throws on, so the original library could not produce this PDF at all.
  const [{ default: html2canvas }, { jsPDF }] = await Promise.all([import("html2canvas-pro"), import("jspdf")]);

  const background = opts.background ?? "#09090b";
  const scale = 2;
  const canvas = await html2canvas(container, {
    scale,
    useCORS: true,
    logging: false,
    backgroundColor: background,
    windowWidth: container.scrollWidth,
    windowHeight: container.scrollHeight,
  });

  const origin = container.getBoundingClientRect().top;
  const blocks: Block[] = Array.from(container.querySelectorAll("[data-pdf-block]")).map((el) => {
    const r = el.getBoundingClientRect();
    return { top: (r.top - origin) * scale, bottom: (r.bottom - origin) * scale };
  });

  const pageW = canvas.width;
  const pageH = Math.round(pageW * A4_RATIO);
  const padTop = Math.round(24 * scale);
  const padBottom = Math.round(40 * scale); // room for the footer
  const pages = planPages(blocks, canvas.height, pageH - padTop - padBottom);

  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const mmW = pdf.internal.pageSize.getWidth();
  const mmH = pdf.internal.pageSize.getHeight();

  pages.forEach((p, i) => {
    const page = document.createElement("canvas");
    page.width = pageW;
    page.height = pageH;
    const ctx = page.getContext("2d");
    if (!ctx) return;
    ctx.fillStyle = background;
    ctx.fillRect(0, 0, pageW, pageH);
    ctx.drawImage(canvas, 0, p.start, pageW, p.end - p.start, 0, padTop, pageW, p.end - p.start);

    ctx.fillStyle = opts.footerColor ?? "#71717a";
    ctx.font = `${11 * scale}px system-ui, -apple-system, "Segoe UI", sans-serif`;
    ctx.textBaseline = "alphabetic";
    const baseline = pageH - Math.round(16 * scale);
    ctx.textAlign = "left";
    ctx.fillText(opts.footer, Math.round(32 * scale), baseline);
    ctx.textAlign = "right";
    ctx.fillText(`Page ${i + 1} of ${pages.length}`, pageW - Math.round(32 * scale), baseline);

    if (i > 0) pdf.addPage();
    // JPEG keeps a dark, mostly flat page small; PNG of the same page was several megabytes.
    pdf.addImage(page.toDataURL("image/jpeg", 0.92), "JPEG", 0, 0, mmW, mmH);
  });

  pdf.save(opts.filename);
}
