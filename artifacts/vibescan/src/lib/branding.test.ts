import { describe, it, expect } from "vitest";
import { brandOf, pdfFilename, pdfFooter, sharedFooter } from "./branding";

describe("brandOf", () => {
  it("reads a brand beside the report", () => {
    expect(brandOf({ brand: { name: "Acme Security", poweredBy: false } })).toEqual({ name: "Acme Security", poweredBy: false });
    expect(brandOf({ brand: { name: "Acme" } })).toEqual({ name: "Acme", poweredBy: true });
  });
  it.each([undefined, null, {}, { brand: null }, { brand: {} }, { brand: { name: "" } }, { brand: { name: "  " } }, { brand: { name: 5 } }, { brand: { name: "x".repeat(61) } }, "brand"])("is no brand for %j", (v) => {
    expect(brandOf(v)).toBeNull();
  });
});

describe("pdfFooter", () => {
  it("is SecScan's own line without a brand", () => {
    expect(pdfFooter(null, "https://secscan.us", "1 Oct 2026")).toBe("Generated by SecScan · https://secscan.us · scanned 1 Oct 2026");
  });
  it("names the brand, with or without a small credit", () => {
    expect(pdfFooter({ name: "Acme", poweredBy: true }, "o", "d")).toBe("Prepared by Acme · scanned d · generated by SecScan");
    expect(pdfFooter({ name: "Acme", poweredBy: false }, "o", "d")).toBe("Prepared by Acme · scanned d");
  });
});

describe("pdfFilename", () => {
  it("is secscan-… by default, and the brand's words when branded", () => {
    expect(pdfFilename(null, "shop.example.com")).toBe("secscan-shop.example.com.pdf");
    expect(pdfFilename({ name: "Acme Security Ltd.", poweredBy: false }, "shop.example.com")).toBe("acme-security-ltd-shop.example.com.pdf");
    expect(pdfFilename({ name: "Acme", poweredBy: false }, null)).toBe("acme-report.pdf");
    expect(pdfFilename({ name: "!!!", poweredBy: false }, null)).toBe("security-report.pdf");
  });
});

describe("sharedFooter", () => {
  it("keeps SecScan's credit and invitation when there is no brand, or the brand keeps the credit", () => {
    expect(sharedFooter(null)).toEqual({ prepared: null, showSecScanCredit: true, showScanCta: true });
    expect(sharedFooter({ name: "Acme", poweredBy: true })).toEqual({ prepared: "Prepared by Acme", showSecScanCredit: true, showScanCta: true });
  });
  it("drops both for a fully branded report", () => {
    expect(sharedFooter({ name: "Acme", poweredBy: false })).toEqual({ prepared: "Prepared by Acme", showSecScanCredit: false, showScanCta: false });
  });
});
